    lr = root / "osfmk" / "arm64" / "loader_return.c"
    bi = root / "bsd" / "kern" / "bsd_init.c"
    text = lr.read_text(encoding="utf-8", errors="surrogateescape")
    if "lafa_fb_text" in text:
        print("patch-fbtext: already patched")
        return 0
    body = EXTRA.replace("FONT_TABLE_HERE", FONT)
    text += body
    lr.write_text(text, encoding="utf-8", errors="surrogateescape")

    b = bi.read_text(encoding="utf-8", errors="surrogateescape")
    if "lafa_fb_text" in b:
        return 0
    b = b.replace("extern void lafa_fb_fill(void);", "extern void lafa_fb_fill(void);\nextern void lafa_fb_text(void);", 1)
    b = b.replace("{lafa_fb_fill();}", "{lafa_fb_fill();\n\t lafa_fb_text();}", 1)
    bi.write_text(b, encoding="utf-8", errors="surrogateescape")
    print("patch-fbtext: kernel text drawing inserted")
    return 0


